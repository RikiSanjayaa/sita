#!/usr/bin/env node
// Helpers for the screenshot catalog (.github/workflows/screenshot-catalog.yml).
// Plain Node, no dependencies.
//
//   node scripts/catalog.mjs index <dir>
//       Write <dir>/README.md: an index of every image under <dir>.
//   node scripts/catalog.mjs sync <newDir> <catalogDir>
//       Update <catalogDir> from <newDir>, rewriting only images that changed
//       beyond rasterization noise (a few anti-aliased edge pixels).
import { Buffer } from 'node:buffer';
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import zlib from 'node:zlib';

function walk(directory, base = directory) {
    if (!fs.existsSync(directory)) {
        return [];
    }

    return fs
        .readdirSync(directory, { withFileTypes: true })
        .flatMap((entry) =>
            entry.isDirectory()
                ? walk(path.join(directory, entry.name), base)
                : entry.name.endsWith('.png')
                  ? [path.relative(base, path.join(directory, entry.name))]
                  : [],
        )
        .sort();
}

/** "mahasiswa/dashboard-1280-light.png" -> { role, page, width, theme } */
function parse(relativePath) {
    const role = path.dirname(relativePath);
    const match = path
        .basename(relativePath, '.png')
        .match(/^(.+)-(\d+)-(light|dark)$/);

    return match
        ? { role, page: match[1], width: match[2], theme: match[3] }
        : {
              role,
              page: path.basename(relativePath, '.png'),
              width: '',
              theme: '',
          };
}

function writeIndex(directory) {
    const files = walk(directory);
    const roles = [...new Set(files.map((file) => parse(file).role))];
    const lines = [
        '# Screenshot catalog',
        '',
        'Generated by `.github/workflows/screenshot-catalog.yml` on every push to `main` (seed data only). Do not edit by hand.',
        'Each page is captured at 1280 and 390 px wide, light and dark, full page.',
        '',
    ];

    for (const role of roles) {
        const pages = [
            ...new Set(
                files
                    .filter((f) => parse(f).role === role)
                    .map((f) => parse(f).page),
            ),
        ];

        lines.push(
            `## ${role}`,
            '',
            '| Page | 1280 light | 1280 dark | 390 light | 390 dark |',
            '| --- | --- | --- | --- | --- |',
        );

        for (const page of pages) {
            const cells = [
                ['1280', 'light'],
                ['1280', 'dark'],
                ['390', 'light'],
                ['390', 'dark'],
            ].map(([width, theme]) => {
                const file = `${role}/${page}-${width}-${theme}.png`;

                return files.includes(file) ? `[png](${encodeURI(file)})` : '-';
            });

            lines.push(`| \`${page}\` | ${cells.join(' | ')} |`);
        }

        lines.push('');
    }

    fs.writeFileSync(path.join(directory, 'README.md'), lines.join('\n'));
}

/** Decodes an 8-bit, non-interlaced RGB/RGBA PNG (what Chromium writes). */
function decodePng(buffer) {
    let offset = 8;
    let header = null;
    const data = [];

    while (offset < buffer.length) {
        const length = buffer.readUInt32BE(offset);
        const type = buffer.toString('latin1', offset + 4, offset + 8);
        const body = buffer.subarray(offset + 8, offset + 8 + length);

        if (type === 'IHDR') {
            header = {
                width: body.readUInt32BE(0),
                height: body.readUInt32BE(4),
                depth: body[8],
                color: body[9],
                interlace: body[12],
            };
        } else if (type === 'IDAT') {
            data.push(body);
        }

        offset += 12 + length;
    }

    if (
        !header ||
        header.depth !== 8 ||
        header.interlace !== 0 ||
        ![2, 6].includes(header.color)
    ) {
        return null;
    }

    const bpp = header.color === 6 ? 4 : 3;
    const stride = header.width * bpp;
    const raw = zlib.inflateSync(Buffer.concat(data));
    const pixels = Buffer.alloc(stride * header.height);

    for (let y = 0; y < header.height; y++) {
        const filter = raw[y * (stride + 1)];
        const line = raw.subarray(y * (stride + 1) + 1, (y + 1) * (stride + 1));
        const row = y * stride;

        for (let x = 0; x < stride; x++) {
            const left = x >= bpp ? pixels[row + x - bpp] : 0;
            const up = y > 0 ? pixels[row - stride + x] : 0;
            const upLeft =
                y > 0 && x >= bpp ? pixels[row - stride + x - bpp] : 0;
            let predictor = 0;

            if (filter === 1) predictor = left;
            else if (filter === 2) predictor = up;
            else if (filter === 3) predictor = (left + up) >> 1;
            else if (filter === 4) {
                const p = left + up - upLeft;
                const pa = Math.abs(p - left);
                const pb = Math.abs(p - up);
                const pc = Math.abs(p - upLeft);
                predictor =
                    pa <= pb && pa <= pc ? left : pb <= pc ? up : upLeft;
            }

            pixels[row + x] = (line[x] + predictor) & 255;
        }
    }

    return { width: header.width, height: header.height, bpp, pixels };
}

// Chromium's anti-aliasing is not always bit-exact between runs: a handful of
// edge pixels of rounded borders and icons move by a few levels. Those must
// not count as a change, a real edit moves far more pixels than this.
const NOISE_LEVEL = 8;
const NOISE_PIXELS = 20;

/** True when the two PNGs differ by more than rasterization noise. */
function isChanged(a, b) {
    if (a.equals(b)) {
        return false;
    }

    const first = decodePng(a);
    const second = decodePng(b);

    if (!first || !second) {
        return true; // undecodable but different bytes
    }

    if (first.width !== second.width || first.height !== second.height) {
        return true;
    }

    let different = 0;

    for (let i = 0; i < first.pixels.length; i += first.bpp) {
        for (let c = 0; c < first.bpp; c++) {
            if (
                Math.abs(first.pixels[i + c] - second.pixels[i + c]) >
                NOISE_LEVEL
            ) {
                different++;
                break;
            }
        }
    }

    return different >= NOISE_PIXELS;
}

/**
 * Brings catalogDir in line with newDir, touching only images that changed
 * (new, changed beyond noise, or gone), so git sees no churn from noise.
 */
function sync(newDir, catalogDir) {
    const before = new Set(walk(catalogDir));
    const after = walk(newDir);

    for (const file of after) {
        const target = path.join(catalogDir, file);

        if (
            !before.has(file) ||
            isChanged(
                fs.readFileSync(target),
                fs.readFileSync(path.join(newDir, file)),
            )
        ) {
            fs.mkdirSync(path.dirname(target), { recursive: true });
            fs.copyFileSync(path.join(newDir, file), target);
        }
    }

    for (const file of before) {
        if (!after.includes(file)) {
            fs.rmSync(path.join(catalogDir, file));
        }
    }
}

const [command, ...args] = process.argv.slice(2);

if (command === 'index' && args[0]) {
    writeIndex(args[0]);
} else if (command === 'sync' && args.length >= 2) {
    sync(args[0], args[1]);
} else {
    console.error('usage: catalog.mjs index <dir> | sync <new> <catalog>');
    process.exit(1);
}
